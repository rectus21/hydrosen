# Kullanim: python tool/make_blink_patches.py assets/caps <tam_blink_png_klasoru> lib/features/thermos/blink_patch_offsets.dart
# Tam boy goz kapali kapaklari normal kapakla karsilastirir, yalniz degisen bolgeyi (+4px) <id>_blink.png olarak yazar.
import sys, glob, os, numpy as np
from PIL import Image
caps=sys.argv[1]; old=sys.argv[2]; M=4
rows=[]
for p in sorted(glob.glob(old+'/*_blink.png')):
    id=os.path.basename(p)[:-10]
    b=Image.open(p).convert('RGBA'); n=Image.open(f'{caps}/{id}_normal.png').convert('RGBA')
    assert b.size==n.size,(id,b.size,n.size)
    d=np.any(np.array(b)!=np.array(n),axis=2)
    ys,xs=np.where(d)
    x0=max(xs.min()-M,0);y0=max(ys.min()-M,0);x1=min(xs.max()+1+M,b.width);y1=min(ys.max()+1+M,b.height)
    b.crop((x0,y0,x1,y1)).save(f'{caps}/{id}_blink.png',optimize=True)
    rows.append((id,x0,y0,x1-x0,y1-y0,b.width,b.height))
with open(sys.argv[3],'w',encoding='utf8') as f:
    f.write("// GENERATED by tool/make_blink_patches.py - elle duzenleme.\n")
    f.write("// Her `<id>_blink.png` yalniz degisen goz bolgesidir; (x, y) normal kapaga gore konumdur.\n\n")
    f.write("/// Goz kirpma yamasinin normal kapaktaki konumu (piksel).\nconst Map<String, ({int x, int y})> kBlinkPatchOffsets = {\n")
    for r in rows: f.write(f"  '{r[0]}': (x: {r[1]}, y: {r[2]}),\n")
    f.write("};\n")
for r in rows: print(r)
